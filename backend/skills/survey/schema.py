# ---------------------------------------------------
# Survey Output
# ---------------------------------------------------

class SurveyOutput(BaseModel):

    question_type: Literal["mcq", "completed"] = Field(
        default="completed",
        description="Type of question: 'mcq' for multiple choice, 'completed' when survey is done"
    )

    status: str

    survey_completed: bool

    profile: StudentProfile

    confidence: float = Field(
        ge=0,
        le=1,
        description="How confident the AI is about the collected profile"
    )

    missing_information: List[str] = Field(
        default_factory=list,
        description="Fields still missing"
    )

    mcq_question_content: Optional[SurveyQuestionContent] = Field(
        default=None,
        description="MCQ question content when question_type is 'mcq' (LLM generated, no IDs)"
    )

    mcq_question: Optional[MCQQuestion] = Field(
        default=None,
        description="MCQ question with backend-generated question_id (populated after validation)"
    )

    coach_notification: Optional[str] = Field(
        default=None,
        description="Completion notification for the Career Coach; never a workflow instruction."
    )
    
    @model_validator(mode='after')
    def validate_question_type_consistency(self) -> 'SurveyOutput':
        if self.question_type == "mcq":
            if self.mcq_question_content is None and self.mcq_question is None:
                raise ValueError("question_type is 'mcq' but both mcq_question_content and mcq_question are None")
        elif self.question_type == "completed":
            if self.mcq_question_content is not None or self.mcq_question is not None:
                raise ValueError("question_type is 'completed' but mcq fields are not None")
        return self
