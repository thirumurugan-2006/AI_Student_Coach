"""
Survey Skill Output Schema

Defines the structured output expected from the LLM.
Separates LLM content generation from backend identifier generation.
"""

from typing import List, Optional, Literal
from pydantic import BaseModel, Field, field_validator, model_validator
from core.skill_output import UniversalSkillOutput


# ---------------------------------------------------
# LLM Output Schema - Content Only
# ---------------------------------------------------

class SurveyQuestionContent(BaseModel):
    """
    Content generated by LLM for Survey questions.
    Does NOT include database identifiers or metadata.
    """
    question: str = Field(
        description="The survey question"
    )
    
    options: List[str] = Field(
        description="List of 4 answer options for the MCQ"
    )
    
    explanation: Optional[str] = Field(
        default=None,
        description="Explanation of the question context (not a correct answer)"
    )
    
    @field_validator('question')
    @classmethod
    def question_must_not_be_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError('question must not be empty')
        return v.strip()
    
    @field_validator('options')
    @classmethod
    def options_must_have_exactly_four(cls, v: List[str]) -> List[str]:
        if len(v) != 4:
            raise ValueError(f'options must have exactly 4 items, got {len(v)}')
        for i, opt in enumerate(v):
            if not opt or not opt.strip():
                raise ValueError(f'option[{i}] must not be empty')
        return [opt.strip() for opt in v]
    
    @field_validator('options')
    @classmethod
    def options_must_be_unique(cls, v: List[str]) -> List[str]:
        normalized = [opt.strip().lower() for opt in v]
        if len(set(normalized)) != len(normalized):
            raise ValueError('options must be unique')
        return v


